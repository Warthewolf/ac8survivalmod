"""landmask.py : Comona's land as runs per 100 m row -> Scripts/sv_ulysses_land.lua (ULYSSES' land / sea test).

    python -I tools/ulysses/landmask.py

From build/research/comona/height_100m.json (docs/re/COMONA_MAP.md section 4: the terrain's own collision mesh sampled at
each 100 m cell; null = sea-only tile). A cell is land when its height is above the sea surface (350 cm) + 50 cm. Each
row (north to south) becomes a string of "first-last" column runs. Why not a trace: hard rule 27 (from Lua a downward
trace only finds terrain near the player; far off it hits the sea planes), and the same answer on every co-op game.
"""
import json
import os
import subprocess

ROOT = subprocess.run(['git', 'rev-parse', '--show-toplevel'], capture_output=True, text=True, check=True).stdout.strip()
MAIN = os.path.dirname(subprocess.run(['git', 'rev-parse', '--path-format=absolute', '--git-common-dir'],
                                      capture_output=True, text=True, check=True).stdout.strip())
SRC = os.path.join(MAIN, 'build', 'research', 'comona', 'height_100m.json')
OUT = os.path.join(ROOT, 'mod', 'UE4SS', 'AC8SurvivalMode', 'Scripts', 'sv_ulysses_land.lua')


def main():
    d = json.load(open(SRC))
    lim = d['sea_surface_z_cm'] + 50
    rows = []
    for r in d['rows']:
        runs, start = [], None
        for c, z in enumerate(r + [None]):
            land = z is not None and z > lim
            if land and start is None:
                start = c
            elif not land and start is not None:
                runs.append('%d-%d' % (start, c - 1))
                start = None
        rows.append(','.join(runs))
    cells = sum(int(b) - int(a) + 1 for row in rows for a, b in (x.split('-') for x in row.split(',') if x))
    lines = ['-- sv_ulysses_land.lua: GENERATED by tools/ulysses/landmask.py (never edit by hand). Comona\'s land at 100 m:',
             '-- each row (north to south) its land cells\' column runs "first-last" (land: the terrain\'s collision height over',
             '-- the sea surface + 0.5 m; %d cells, %.1f km2). ULY.isLand(x, y) (cm) in sv_ulysses.lua reads it.' % (cells, cells / 100),
             'ULY = ULY or {}',
             'ULY.LAND = { x0 = %.0f, y0 = %.0f, cell = %.0f, w = %d, h = %d, rows = {' % (d['x0_cm'], d['y0_cm'], d['cell_cm'],
                                                                                           d['width'], d['height'])]
    for row in rows:
        lines.append('    "%s",' % row)
    lines.append('} }')
    open(OUT, 'w', newline='\n').write('\n'.join(lines) + '\n')
    print('landmask: %d rows, %d land cells (%.1f km2) -> %s' % (len(rows), cells, cells / 100, OUT))


if __name__ == '__main__':
    main()
