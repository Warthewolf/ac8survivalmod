/* a snippet at a 16-aligned copy (the real functions start 16-aligned: call targets keep their alignment), call targets
 * counted within 256 MB of it (the game's image is 0x2195a000 long) */
static uint32_t Detect(const uint8_t* code, size_t len, size_t n)
{
    uint8_t* buf = _aligned_malloc(len + 16, 16);
    memcpy(buf, code, len);
    memset(buf + len, 0xCC, 16);
    uint32_t m = UoEventObjs(buf, n, buf - 0x10000000, buf + 0x10000000);
    _aligned_free(buf);
    return m;
}

