        memset(pad, 0xCC, sizeof(pad)); memcpy(pad, r13, sizeof(r13));
        check(Detect(pad, sizeof(pad), sizeof(r13)) == (1u << 3), "made up: r13 a copy, r8 = its +0x18, tested: +0x18");
