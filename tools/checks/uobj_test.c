        static const uint8_t cmp[] = { 0x48, 0x8B, 0x41, 0x18, 0x48, 0x3B, 0xC2, 0x0F, 0x94, 0xC0, 0xC3 };
        memset(pad, 0xCC, sizeof(pad)); memcpy(pad, cmp, sizeof(cmp));
