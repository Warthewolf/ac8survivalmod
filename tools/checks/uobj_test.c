        static uint8_t pad[0x60];
        /* rcx reloaded from the trigger (+0x40) first: the +0x18 it tests is the trigger's, not the event's */
        static const uint8_t trig[] = { 0x48, 0x8B, 0x4A, 0x40, 0x48, 0x8B, 0x41, 0x18, 0x48, 0x85, 0xC0, 0x74, 0x0A, 0x8B, 0x40, 0x08,
                                        0xC1, 0xE8, 0x1E, 0xC3 };
        memset(pad, 0xCC, sizeof(pad)); memcpy(pad, trig, sizeof(trig));
        check(Detect(pad, sizeof(pad), sizeof(trig)) == 0, "made up: rcx reloaded before the load: nothing");
